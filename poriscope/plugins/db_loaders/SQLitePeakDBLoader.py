import logging
from typing import List, Optional, Tuple, override

import numpy as np
import pandas as pd

from poriscope.plugins.db_loaders.SQLiteDBLoader import SQLiteDBLoader
from poriscope.utils.DocstringDecorator import inherit_docstrings
from poriscope.utils.LogDecorator import log


@inherit_docstrings
class SQLitePeakDBLoader(SQLiteDBLoader):
    """
    Subclass of MetaDatabaseLoader for reading and querying SQLite database files.

    Provides functionality to load metadata, event data, and other relevant
    structures from a structured SQLite database generated by Poriscope.
    """

    logger = logging.getLogger(__name__)

    #: Event columns this plot uses that a database may predate. An unknown
    #: column is a hard error in SQLite, not a NULL, so naming one
    #: unconditionally would take the whole plot down on any file written
    #: before that column existed - ``bound_star`` being the newest. Each is
    #: added to the query only once the database is known to carry it, and the
    #: label simply omits the field otherwise.
    OPTIONAL_EVENT_COLUMNS = (
        "unfolded_level",
        "sequence",
        "translocation_direction",
        "translocation_confidence",
        "bound_star",
    )

    #: The same, for sublevel columns.
    OPTIONAL_SUBLEVEL_COLUMNS = ("classified", "classification_confidence")

    @log(logger=logger)
    @override
    def get_plot_features(self, experiment: int, channel: int, index: int) -> Tuple[
        Optional[List[float]],
        Optional[List[float]],
        Optional[List[Tuple[float, float]]],
        Optional[List[str]],
        Optional[List[str]],
        Optional[List[str]],
    ]:
        """
        Get a list of horizontal and vertical lines and associated labels to overlay on the graph generated by construct_fitted_event()

        :param experiment: get only events from this experiment
        :type experiment: int
        :param channel: analyze only events from this channel
        :type channel: int
        :param index: the index of the target event
        :type index: int

        :return: a list of x locations to plot vertical lines and a list of y locations to plot horizontal lines, list of tuples to plot little x's, labels for the vertical lines, labels for the horizontal lines, labels for x's. Must be lists of equal length, or None
        :rtype: Tuple[Optional[List[float]], Optional[List[float]], Optional[List[Tuple[float, float]]], Optional[List[str]], Optional[List[str]], Optional[List[str]]]
        """

        try:
            # Ask the database which optional columns it actually has. When
            # introspection returns nothing we cannot tell "absent" from
            # "unknown", so every optional column is requested and a genuinely
            # missing one fails loudly - better than silently dropping fields
            # from a database that does carry them.
            event_columns = self.get_column_names_by_table("events")
            sublevel_columns = self.get_column_names_by_table("sublevels")
            event_optional = [
                name
                for name in self.OPTIONAL_EVENT_COLUMNS
                if event_columns is None or name in event_columns
            ]
            sublevel_optional = [
                name
                for name in self.OPTIONAL_SUBLEVEL_COLUMNS
                if sublevel_columns is None or name in sublevel_columns
            ]

            selected = (
                [
                    "s.id",
                    "s.experiment_id",
                    "s.channel_id",
                    "s.event_id",
                    "s.peak_id",
                    "s.peak_loc",
                    "s.peak_height",
                    "s.left_base",
                    "s.right_base",
                    "s.right_ips",
                    "s.filtered",
                    "s.sublevel_start_times",
                    "e.baseline_current",
                    "e.baseline_stdev",
                ]
                + [f"s.{name}" for name in sublevel_optional]
                + [f"e.{name}" for name in event_optional]
            )

            query = f"""SELECT {", ".join(selected)}
                        FROM sublevels s
                        JOIN events e
                        ON e.id = s.event_db_id
                        WHERE s.experiment_id={experiment} AND s.channel_id={channel} AND s.event_id={index}"""

        except Exception as e:
            # NOTE (integration): this handler had lost its `return`, so a failure
            # while building the query fell straight through to
            # validate_filter_query(query) with `query` never assigned - a NameError
            # instead of the clean "no features to plot" result the caller expects.
            # Restored the early return.
            self.logger.debug(
                f"Error constructing query in get_plot_features: {str(e)}",
                self.__class__.__name__,
            )
            return None, None, None, None, None, None

        valid, debug = self.validate_filter_query(query)
        if valid:
            result = self.query_database_directly(query)
            # NOTE (integration): the `result is None` half of this guard had been
            # dropped. query_database_directly() returns None when the query yields
            # nothing, and len(None) raises TypeError, so the None case has to be
            # tested before the length. Restored.
            if result is None or len(result) == 0:
                self.logger.info(
                    "Empty dataframe, no features to plot for event",
                    self.__class__.__name__,
                )
                return None, None, None, None, None, None
        else:
            self.logger.debug(
                f"Invalid query syntax in get_plot_features: {self._format_debug_msg(debug)}",
                self.__class__.__name__,
            )
            return None, None, None, None, None, None

        bases = []
        peaks = []
        vlabel = []
        hlabel = []
        plabel = []
        peaks_filtered = []

        # --- 1. Handle Event-Level Data ---
        # Grab the first row for event-level metrics (since they are identical across all rows for this event)
        first_row = result.iloc[0]
        event_first = result.iloc[1]
        event_last = result.iloc[-1]
        baseline = (
            first_row["baseline_current"]
            if "baseline_current" in first_row
            else first_row["baseline"]
        )
        unfolded = (
            first_row["unfolded_level"] if "unfolded_level" in first_row else None
        )
        sequence = first_row["sequence"] if "sequence" in first_row else None
        direction = (
            first_row["translocation_direction"]
            if "translocation_direction" in first_row
            else None
        )
        translocation_confidence = (
            first_row["translocation_confidence"]
            if "translocation_confidence" in first_row
            else None
        )
        bound_star = first_row["bound_star"] if "bound_star" in first_row else None
        event_start = event_first["sublevel_start_times"]
        event_end = event_last["sublevel_start_times"]
        # std = first_row["baseline_std"]
        sign = np.sign(baseline)

        # Only fields the row actually carries are written into the label. An
        # event the classifiers never reached should read as having no value
        # there, not as having a value of nan, which looks like a
        # classification that ran and failed. Keyed off the direction rather
        # than the sequence, since the direction is what the branch below
        # actually needs. Mirrors PeakFinder.get_plot_features - the two draw
        # the same event, one from live fit state and one from a saved
        # database, so they should read identically.
        if direction in ("forward", "backward"):
            peaks_filtered.append(event_start if direction == "forward" else event_end)

            # bound_star shares the direction's line: it is the same
            # long-end/short-end question answered from the star's position
            # rather than from the ECD ratio, so the two belong side by side.
            label = f"{direction.capitalize()} translocation."
            if pd.notna(bound_star) and bound_star:
                label += f" Bound star: {bound_star}"

            fields = []
            if pd.notna(sequence) and sequence:
                fields.append(f"Sequence: {sequence}")
            if translocation_confidence is not None and pd.notna(
                translocation_confidence
            ):
                fields.append(
                    f"Confidence: {round(float(translocation_confidence), 3)}"
                )
            if fields:
                label += "\n " + " ".join(fields)

            vlabel.append(label)

        bases.append(baseline)
        hlabel.append("Baseline")

        # NOTE (integration): this pair was previously guarded by
        # `if unfolded is not None:`. The guard was removed, but the line above still
        # assigns None when the "unfolded_level" column is missing from the row, so
        # the arithmetic here raised TypeError in exactly that case. Guard restored.
        if unfolded is not None:
            bases.append(baseline - sign * unfolded)
            hlabel.append("unfolded level")

        # bases.append(-sign * unfolded + baseline - sign * std)
        # hlabel.append("unfolded level + std")

        # bases.append(-sign * unfolded + baseline + sign * std)
        # hlabel.append("unfolded level - std")

        # --- 2. Handle Sublevel Data ---
        # Iterate over all rows using itertuples for speed
        j = 1
        for row in result.itertuples():
            # Check if peak_id is valid (pd.notna safely handles None/NaN in pandas)
            if pd.notna(row.peak_id):

                # No need for [i] indexing anymore, `row` represents the specific sublevel
                # bases.append(baseline - sign * row.left_base)
                # bases.append(baseline - sign * row.right_base)

                # hlabel.append(f"Right base #{j}")
                # hlabel.append(f"Left base #{j}")

                peaks.append((row.peak_loc, baseline - sign * row.peak_height))

                # Same rule as the event label above: a peak no classifier
                # acted on - every filter type -1 among them - carries NaN in
                # "classified" and "classification_confidence", and those are
                # left out rather than printed as nan. getattr because the
                # column may not have been selected at all on an older
                # database.
                peak_label = "Peak #" + str(j)
                filtered_value = getattr(row, "filtered", None)
                if pd.notna(filtered_value):
                    peak_label += f" Filter: {filtered_value}"
                class_value = getattr(row, "classified", None)
                if pd.notna(class_value):
                    peak_label += f" Class: {class_value}"
                confidence_value = getattr(row, "classification_confidence", None)
                if confidence_value is not None and pd.notna(confidence_value):
                    peak_label += f" Confidence: {round(float(confidence_value), 3)}"
                plabel.append(peak_label)

                # Filter logic
                # if row.filtered not in (0, -1):
                #     peaks_filtered.append(row.peak_loc)
                #     vlabel.append(f"Type {row.filtered} Peak {j}")

                j += 1
        return peaks_filtered, bases, peaks, vlabel, hlabel, plabel
